"""
Train Tiny CNN 96x96 INT8 cho ESP32-CAM — nhận diện bệnh lá (dataset Beans HF).
Xuất: models/leaf_int8.tflite + firmware/model_data.h
"""
from __future__ import annotations

import json
import os
from pathlib import Path

import numpy as np
import tensorflow as tf

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "pipeline" / "models"
FW = ROOT / "firmware" / "ESP32_CAM_LeafAI"
OUT.mkdir(parents=True, exist_ok=True)
FW.mkdir(parents=True, exist_ok=True)

IMG = 96
BATCH = 32
EPOCHS = 12
SEED = 42


def load_beans():
    """Dataset lá đậu (HF beans parquet): angular_leaf_spot / bean_rust / healthy."""
    import io
    import urllib.request
    from PIL import Image
    import pyarrow.parquet as pq

    data_dir = OUT / "ibeans_pq"
    data_dir.mkdir(parents=True, exist_ok=True)
    urls = {
        "train": "https://huggingface.co/datasets/beans/resolve/main/data/train-00000-of-00001.parquet",
        "validation": "https://huggingface.co/datasets/beans/resolve/main/data/validation-00000-of-00001.parquet",
        "test": "https://huggingface.co/datasets/beans/resolve/main/data/test-00000-of-00001.parquet",
    }
    class_names = ["dom_la_goc", "gi_sat_la", "khoe_manh"]  # 0,1,2 đúng thứ tự HF beans
    print("Classes:", class_names)

    def ensure(name: str) -> Path:
        path = data_dir / f"{name}.parquet"
        if path.exists() and path.stat().st_size > 1000:
            return path
        print("Downloading", name)
        req = urllib.request.Request(urls[name], headers={"User-Agent": "Mozilla/5.0"})
        with urllib.request.urlopen(req, timeout=180) as r, open(path, "wb") as f:
            f.write(r.read())
        return path

    def load_split(name: str):
        table = pq.read_table(ensure(name))
        images = table.column("image").to_pylist()
        labels = table.column("labels").to_pylist()
        xs, ys = [], []
        for img_obj, lab in zip(images, labels):
            raw = img_obj["bytes"] if isinstance(img_obj, dict) else img_obj
            img = Image.open(io.BytesIO(raw)).convert("RGB").resize((IMG, IMG))
            xs.append(np.asarray(img, dtype=np.float32) / 255.0)
            ys.append(int(lab))
        return np.stack(xs), np.array(ys, dtype=np.int32)

    x_train, y_train = load_split("train")
    x_val, y_val = load_split("validation")
    x_test, y_test = load_split("test")
    return (x_train, y_train), (x_val, y_val), (x_test, y_test), class_names


def build_tiny_cnn(num_classes: int) -> tf.keras.Model:
    """CNN cực nhẹ — phù hợp ESP32-CAM (~1 FPS mục tiêu)."""
    inputs = tf.keras.Input(shape=(IMG, IMG, 3))
    x = tf.keras.layers.Conv2D(16, 3, strides=2, padding="same", activation="relu")(inputs)
    x = tf.keras.layers.MaxPool2D()(x)
    x = tf.keras.layers.Conv2D(32, 3, padding="same", activation="relu")(x)
    x = tf.keras.layers.MaxPool2D()(x)
    x = tf.keras.layers.Conv2D(64, 3, padding="same", activation="relu")(x)
    x = tf.keras.layers.GlobalAveragePooling2D()(x)
    x = tf.keras.layers.Dropout(0.2)(x)
    outputs = tf.keras.layers.Dense(num_classes, activation="softmax")(x)
    model = tf.keras.Model(inputs, outputs, name="tiny_leaf_cnn")
    model.compile(
        optimizer=tf.keras.optimizers.Adam(1e-3),
        loss="sparse_categorical_crossentropy",
        metrics=["accuracy"],
    )
    return model


def representative_data_gen(x_train):
    for i in range(min(100, len(x_train))):
        yield [x_train[i : i + 1].astype(np.float32)]


def convert_int8(model, x_train) -> bytes:
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = lambda: representative_data_gen(x_train)
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    tflite_model = converter.convert()
    return tflite_model


def write_c_header(tflite_bytes: bytes, class_names: list[str], path: Path):
    arr = ", ".join(str(b) for b in tflite_bytes)
    labels = ",\n  ".join(f'"{n}"' for n in class_names)
    content = f"""#pragma once
// Auto-generated by pipeline/train_tiny_leaf.py — Tiny Leaf Disease INT8
#include <Arduino.h>

const unsigned int leaf_model_len = {len(tflite_bytes)};
alignas(8) const unsigned char leaf_model[] = {{
  {arr}
}};

const int LEAF_NUM_CLASSES = {len(class_names)};
const char* const LEAF_LABELS[LEAF_NUM_CLASSES] = {{
  {labels}
}};

const int LEAF_IMG_SIZE = {IMG};
"""
    path.write_text(content, encoding="utf-8")
    print("Wrote", path, "bytes", len(tflite_bytes))


def main():
    tf.keras.utils.set_random_seed(SEED)
    (x_train, y_train), (x_val, y_val), (x_test, y_test), class_names = load_beans()
    print("train", x_train.shape, "val", x_val.shape, "test", x_test.shape)

    model = build_tiny_cnn(len(class_names))
    model.summary()

    cb = [
        tf.keras.callbacks.EarlyStopping(patience=3, restore_best_weights=True, monitor="val_accuracy"),
        tf.keras.callbacks.ReduceLROnPlateau(patience=2, factor=0.5, monitor="val_loss"),
    ]
    model.fit(
        x_train,
        y_train,
        validation_data=(x_val, y_val),
        epochs=EPOCHS,
        batch_size=BATCH,
        callbacks=cb,
        verbose=1,
    )
    loss, acc = model.evaluate(x_test, y_test, verbose=0)
    print(f"Test accuracy: {acc:.4f}")

    float_path = OUT / "leaf_float.keras"
    model.save(float_path)

    print("Converting INT8...")
    tflite_model = convert_int8(model, x_train)
    tflite_path = OUT / "leaf_int8.tflite"
    tflite_path.write_bytes(tflite_model)
    print("TFLite size KB:", round(len(tflite_model) / 1024, 2))

    # sanity check interpreter
    interp = tf.lite.Interpreter(model_content=tflite_model)
    interp.allocate_tensors()
    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    print("input", inp["dtype"], inp["shape"], "scale/zp", inp.get("quantization"))
    print("output", out["dtype"], out["shape"], "scale/zp", out.get("quantization"))

    meta = {
        "classes": class_names,
        "img": IMG,
        "test_accuracy": float(acc),
        "tflite_kb": round(len(tflite_model) / 1024, 2),
        "dataset": "huggingface:beans (leaf disease proxy)",
    }
    (OUT / "meta.json").write_text(json.dumps(meta, indent=2), encoding="utf-8")

    write_c_header(tflite_model, class_names, FW / "model_data.h")
    write_c_header(tflite_model, class_names, OUT / "model_data.h")
    print("DONE")


if __name__ == "__main__":
    main()
